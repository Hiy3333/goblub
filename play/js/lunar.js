  function leapMonth(y) { return INFO[y - 1900] & 0xf; }               // 그 해의 윤달(없으면 0)
  function leapDays(y) { return leapMonth(y) ? ((INFO[y - 1900] & 0x10000) ? 30 : 29) : 0; }
  function monthDays(y, m) { return (INFO[y - 1900] & (0x10000 >> m)) ? 30 : 29; }
  function yearDays(y) {
    var s = 348;
    for (var i = 0x8000; i > 0x8; i >>= 1) s += (INFO[y - 1900] & i) ? 1 : 0;
    return s + leapDays(y);
  }
  // 음력 y년 m월 d일(isLeap=윤달)을 양력 {y,m,d}로. 무효 입력이면 null.
  function lunarToSolar(y, m, d, isLeap) {
    if (!(y >= 1900 && y <= 2100) || !(m >= 1 && m <= 12)) return null;
    var lm = leapMonth(y);
    if (isLeap && lm !== m) return null;                 // 그 해에 없는 윤달
    var mx = isLeap ? leapDays(y) : monthDays(y, m);
    if (!(d >= 1 && d <= mx)) return null;               // 그 달에 없는 날
    var off = 0;
    for (var yy = 1900; yy < y; yy++) off += yearDays(yy);
    for (var mm = 1; mm < m; mm++) { off += monthDays(y, mm); if (lm === mm) off += leapDays(y); }
    if (isLeap) off += monthDays(y, m);
    off += d - 1;
    var t = new Date(1900, 0, 31);                        // 1900-01-31 = 음력 1900년 1월 1일
    t.setDate(t.getDate() + off);
    return { y: t.getFullYear(), m: t.getMonth() + 1, d: t.getDate() };
  }
  window.GoblubLunar = { leapMonth: leapMonth, monthDays: monthDays, leapDays: leapDays, lunarToSolar: lunarToSolar };
