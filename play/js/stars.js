  var OH = ["목", "화", "토", "금", "수"];
  function ganOh(g) { return OH[Math.floor(g / 2)]; }

  /* ── 군 안에서 고르게 나누는 값 ────────────────────────────────
     일주만 쓰면 군을 가르는 조건과 값이 붙어 버려 몇 자리가 아예 안 나온다.
     연·월·시주까지 섞고, A·B 를 바꿔도 같은 값이 나오도록 대칭식으로 만든다. */
  function spread(rA, rB) {
    function v(p) { return p ? (p[0] * 13 + p[1] * 7 + 5) : 11; }
    function side(r) {
      var p = r.pillars;
      return v(p.year) * 3 + v(p.month) * 5 + v(p.day) * 11 + v(p.hour);
    }
    var x = side(rA), y = side(rB);
    return (x * y + x + y) % 997;          // 곱·합만 써서 순서에 무관
  }

  /* ── 판정 ─────────────────────────────────────────────────── */
  function pick(s, rA, rB) {
    var il = s.ilgan.type, ij = s.ilji.type, oh = s.oheng.type, tt = s.tti.type;
    var sameTti = rA.pillars.year[1] === rB.pillars.year[1];
    var lbA = rA.strength.label, lbB = rB.strength.label;
    var gap = Math.abs(rA.strength.ratio - rB.strength.ratio);

    var idx = null;
    /* ① 드문 자리 — 조건이 까다로운 순서대로.
       (주의: 60갑자에서 '일간 천간합'과 '일지 충'은 간지 짝수·홀수가 어긋나
        절대 같이 나오지 않는다. 은하수자리는 일지·띠가 모두 충인 경우로 잡는다.) */
    if (s.total >= 94) idx = 35;                                          // 아직 이름 없는 자리
    else if (ij === "충" && tt === "충" && il === "상극") idx = 31;        // 일식
    else if (ij === "충" && tt === "충") idx = 30;                         // 은하수
    else if (il === "상생" && gap >= 0.30 &&
             ((lbA === "신강" && lbB === "신약") ||
              (lbA === "신약" && lbB === "신강"))) idx = 32;               // 북극성
    else if (il === "비겁" && sameTti && ij !== "충") idx = 33;            // 한 뿌리
    else if (oh === "결핍" && ij === "평" && il === "비겁" && gap < 0.05) idx = 34; // 새벽

    if (idx === null) {
      /* ② 나머지 — '얼마나 이어졌나(bond)'와 '얼마나 부딪히나(clash)',
            '얼마나 기울었나(gap)'로 군을 고른다. 한 군에 몰리지 않게 나눈 값이다. */
      var bond =
        ({ 육합: 3, 삼합: 2, 평: 1, 충: 0 })[ij] +
        ({ 천간합: 3, 상생: 2, 비겁: 1, 상극: 0 })[il] +
        ({ 육합: 1, 삼합: 1, 평: 0, 충: -1 })[tt] +
        (oh === "결핍" ? 0 : 1);
      var clash = (ij === "충" ? 1 : 0) + (il === "상극" ? 1 : 0) + (tt === "충" ? 1 : 0);

      var base;
      if (bond >= 5) base = 0;                       // 얽힘
      else if (clash >= 1 && bond >= 2) base = 6;    // 부딪힘 — 가까운데 부딪힌다
      else if (gap >= 0.22) base = 12;               // 기욺 — 한쪽으로 확 쏠림
      else if (bond <= 1) base = 24;                 // 멀어짐
      else base = 18;                                // 나란함
      idx = base + (spread(rA, rB) % 6);
    }

    var c = C[idx];
    // 기울어진 자리는 '무거운 쪽'이 왼쪽에 오도록 좌우를 맞춘다
    var flip = (c.g === 3 || c.key === "polaris") &&
               rB.strength.ratio > rA.strength.ratio;

    var ganA = rA.pillars.day[0], jiA = rA.pillars.day[1];
    var ganB = rB.pillars.day[0], jiB = rB.pillars.day[1];
    var mag = magOf(s.total);
    var domA = ganOh(ganA), domB = ganOh(ganB);
    var obs = {
      season: SEASON[(jiA + jiB) % 4],
      hour: HOUR[(ganA + ganB) % 4],
      dir: DIR[OH[(Math.floor(ganA / 2) + Math.floor(ganB / 2)) % 5]]
    };

    return {
      idx: idx, key: c.key, group: c.g,
      name: c.name, sub: c.sub, desc: c.desc, care: c.care,
      naming: !!c.naming,
      pts: c.pts, links: c.links, flip: flip,
      mag: mag, magText: MAG[mag],
      colorA: OHC[domA], colorB: OHC[domB], ohA: domA, ohB: domB,
      obs: obs,
      obsText: obs.season + " " + obs.hour + ", " + obs.dir + " 하늘에서 가장 높이 뜹니다"
    };
  }

